-- Team captains and tournament applications.
-- Safe to run more than once. Existing teams, users and tournaments are preserved.
BEGIN;
ALTER TABLE public.mvp_tournaments
  ADD COLUMN IF NOT EXISTS allow_captain_registration BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE IF NOT EXISTS public.mvp_team_captains (
  team_id BIGINT PRIMARY KEY REFERENCES public.teams(id) ON DELETE CASCADE,
  user_id UUID NOT NULL UNIQUE REFERENCES public.mvp_auth_users(id) ON DELETE CASCADE,
  assigned_by UUID REFERENCES public.mvp_auth_users(id) ON DELETE SET NULL,
  assigned_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS mvp_team_captains_user_idx
  ON public.mvp_team_captains(user_id);

CREATE TABLE IF NOT EXISTS public.mvp_tournament_applications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tournament_id BIGINT NOT NULL REFERENCES public.mvp_tournaments(id) ON DELETE CASCADE,
  team_id BIGINT NOT NULL REFERENCES public.teams(id) ON DELETE CASCADE,
  captain_user_id UUID NOT NULL REFERENCES public.mvp_auth_users(id) ON DELETE CASCADE,
  status TEXT NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending','approved','rejected')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  reviewed_at TIMESTAMPTZ,
  reviewed_by UUID REFERENCES public.mvp_auth_users(id) ON DELETE SET NULL,
  admin_note TEXT NOT NULL DEFAULT '',
  UNIQUE (tournament_id, team_id)
);
CREATE INDEX IF NOT EXISTS mvp_tournament_applications_status_idx
  ON public.mvp_tournament_applications(status, created_at DESC);
CREATE INDEX IF NOT EXISTS mvp_tournament_applications_tournament_idx
  ON public.mvp_tournament_applications(tournament_id, status);

REVOKE ALL ON public.mvp_team_captains FROM PUBLIC;
REVOKE ALL ON public.mvp_tournament_applications FROM PUBLIC;
COMMIT;
