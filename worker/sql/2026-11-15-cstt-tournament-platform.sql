-- Preserve the existing bracket shape and completed/live state for legacy events.
UPDATE public.mvp_tournaments
SET event_status = CASE
  WHEN status = 'completed' THEN 'completed'
  WHEN status = 'live' THEN 'live'
  ELSE 'upcoming'
END,
team_count = CASE
  WHEN CASE
    WHEN jsonb_typeof(bracket_data->'lower_teams') = 'array'
      THEN jsonb_array_length(bracket_data->'lower_teams') > 0
    ELSE FALSE
  END THEN 16
  ELSE 8
END;

ALTER TABLE public.mvp_tournaments
  ALTER COLUMN organizer_id SET NOT NULL;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'mvp_tournaments_organizer_id_fkey'
      AND conrelid = 'public.mvp_tournaments'::regclass
  ) THEN
    ALTER TABLE public.mvp_tournaments
      ADD CONSTRAINT mvp_tournaments_organizer_id_fkey
      FOREIGN KEY (organizer_id) REFERENCES public.mvp_tournament_organizers(id)
      ON DELETE CASCADE;
  END IF;
END $$;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'mvp_tournaments_event_status_check'
      AND conrelid = 'public.mvp_tournaments'::regclass
  ) THEN
    ALTER TABLE public.mvp_tournaments
      ADD CONSTRAINT mvp_tournaments_event_status_check
      CHECK (event_status IN ('upcoming','live','completed'));
  END IF;
END $$;

ALTER TABLE public.mvp_tournaments
  DROP CONSTRAINT IF EXISTS mvp_tournaments_team_count_check;
ALTER TABLE public.mvp_tournaments
  ADD CONSTRAINT mvp_tournaments_team_count_check
  CHECK (team_count BETWEEN 2 AND 64);

CREATE INDEX IF NOT EXISTS idx_mvp_tournaments_organizer_status_date
  ON public.mvp_tournaments (organizer_id, event_status, start_date, updated_at DESC);
CREATE INDEX IF NOT EXISTS idx_mvp_tournament_organizers_active_sort
  ON public.mvp_tournament_organizers (is_active, sort_order, name);

