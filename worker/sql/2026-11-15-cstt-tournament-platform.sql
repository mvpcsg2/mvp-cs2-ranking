-- CSTT multi-organizer tournament platform
-- Run once in the production SQL editor before using tournament companies.

CREATE TABLE IF NOT EXISTS public.mvp_tournament_organizers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL CHECK (char_length(btrim(name)) BETWEEN 2 AND 80),
  slug TEXT NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9-]{2,80}$'),
  logo_url TEXT NOT NULL DEFAULT '',
  description TEXT NOT NULL DEFAULT '',
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  sort_order INTEGER NOT NULL DEFAULT 100,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  created_by UUID
);

ALTER TABLE public.mvp_tournaments
  ADD COLUMN IF NOT EXISTS organizer_id BIGINT,
  ADD COLUMN IF NOT EXISTS prize_pool NUMERIC(14,2) NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS prize_currency VARCHAR(8) NOT NULL DEFAULT 'USD',
  ADD COLUMN IF NOT EXISTS team_count INTEGER NOT NULL DEFAULT 8,
  ADD COLUMN IF NOT EXISTS description TEXT NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS start_date DATE,
  ADD COLUMN IF NOT EXISTS end_date DATE,
  ADD COLUMN IF NOT EXISTS event_status TEXT NOT NULL DEFAULT 'upcoming';

